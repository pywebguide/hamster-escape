// Уровни игры «Хомячий побег».
// Легенда карты:
//   #  стена            .  пусто             -  полочка (запрыгнуть можно снизу)
//   ^  канцелярские кнопки (опасно)          ~  треснувшая доска (ломается под Пончиком и коробкой)
//   T  пружина          k  коробка           *  семечка (в каждом уровне три)
//   1  Пончик           2  Коготок           3  Шустрик
//   E  норка-выход      =  лифт (куда едет, задаёт lifts)
//   a b c  кнопки       A B C  двери (открываются кнопкой своей буквы)
//   F  вентилятор (дует вверх, поднимает Коготка и Шустрика, Пончика — нет)
//   o p q  хомячьи трубы: две одинаковые буквы — два конца одной трубы (Пончик не пролезает)
//   < >  конвейер (везёт в сторону стрелки)    %  кусты (в них кот не видит)
//   @  кот Граф (спит, ворочается, просыпается и смотрит; трогать нельзя)
// Настройки уровня: heavy — какие кнопки тяжёлые, latch — какие остаются нажатыми,
// timer — кнопки с часиками {a: 4} (держатся 4 секунды после того, как с них сошли),
// lifts — для каждого лифта слева направо: канал кнопки и смещение {ch, dx, dy},
// fans — для каждого вентилятора по порядку: {ch, inv, range} (inv — кнопка выключает, range — высота потока),
// belts — для каждого конвейера по порядку: {ch, run} (кнопка разворачивает; с run — включает),
// cats — для каждого кота: {face, sleep, warn, awake, turn, off, range}.
